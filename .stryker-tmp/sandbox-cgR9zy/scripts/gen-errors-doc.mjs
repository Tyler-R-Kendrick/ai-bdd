#!/usr/bin/env node
// @ts-nocheck
// Generates docs/errors.md from ERROR_CODES in packages/sdk/src/contracts/index.ts.
//   node scripts/gen-errors-doc.mjs           write the file
//   node scripts/gen-errors-doc.mjs --check   fail when the file differs from what would be generated
import fs from 'node:fs';
import path from 'node:path';
import { isMain, listPackages, parseArgs, toPosix, walk } from './lib.mjs';

const CONTRACTS = 'packages/sdk/src/contracts/index.ts';
const OUTPUT = 'docs/errors.md';

function quotedStrings(block) {
  return [...block.matchAll(/'([A-Z][A-Z0-9_]*)'|"([A-Z][A-Z0-9_]*)"/g)].map((m) => m[1] ?? m[2]);
}

/** Parses the code list and the retryable set out of the contracts source text. */
export function parseContracts(source) {
  const codes = /\bERROR_CODES\s*=\s*\[([\s\S]*?)\]\s*as\s+const/.exec(source);
  if (!codes) throw new Error(`ERROR_CODES array literal not found in ${CONTRACTS}`);
  const retry = /\bRETRYABLE_CODES\b[^=]*=\s*new\s+Set\s*(?:<[^>]*>)?\s*\(\s*\[([\s\S]*?)\]\s*\)/.exec(source);
  return { codes: quotedStrings(codes[1]), retryable: new Set(retry ? quotedStrings(retry[1]) : []) };
}

export function groupOf(code) {
  const i = code.indexOf('_');
  return i === -1 ? 'general' : code.slice(0, i).toLowerCase();
}

export function describeCode(code) {
  const words = code.toLowerCase().split('_');
  words[0] = words[0][0].toUpperCase() + words[0].slice(1);
  return `${words.join(' ')}.`;
}

/** Codes quoted in any package source (outside the contracts file), package test or top-level test. */
export function referencedCodes(root, codes) {
  const dirs = [path.join(root, 'tests')];
  for (const pkg of listPackages(root)) {
    dirs.push(path.join(root, 'packages', pkg, 'src'), path.join(root, 'packages', pkg, 'test'));
  }
  const referenced = new Set();
  const remaining = new Set(codes);
  for (const d of dirs) {
    for (const f of walk(d, { filter: (x) => /\.[cm]?[jt]sx?$/.test(x) })) {
      if (toPosix(path.relative(root, f)) === CONTRACTS) continue;
      const text = fs.readFileSync(f, 'utf8');
      for (const code of [...remaining]) {
        if (new RegExp(`['"\`]${code}['"\`]`).test(text)) {
          referenced.add(code);
          remaining.delete(code);
        }
      }
      if (remaining.size === 0) return referenced;
    }
  }
  return referenced;
}

export function renderErrorsDoc({ codes, retryable, referenced }) {
  const lines = [
    '# Error codes',
    '',
    `<!-- Generated by scripts/gen-errors-doc.mjs from ${CONTRACTS}. Do not edit; run \`node scripts/gen-errors-doc.mjs\`. -->`,
    '',
    'Every `ERROR_CODES` entry of `@ai-bdd/sdk/contracts`. A code is `reserved` when no package source (outside the contracts file) or test refers to it yet.',
    '',
    '| Code | Retryable | Group | Description | Status |',
    '|---|---|---|---|---|',
  ];
  for (const code of codes) {
    lines.push(
      `| \`${code}\` | ${retryable.has(code) ? 'yes' : 'no'} | ${groupOf(code)} | ${describeCode(code)} | ${referenced.has(code) ? 'referenced' : 'reserved'} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}

export function generateErrorsDoc(root) {
  const source = fs.readFileSync(path.join(root, CONTRACTS), 'utf8');
  const { codes, retryable } = parseContracts(source);
  return renderErrorsDoc({ codes, retryable, referenced: referencedCodes(root, codes) });
}

/** Writes (or, with `check`, verifies) docs/errors.md. */
export function run(root, { check = false } = {}) {
  const expected = generateErrorsDoc(root);
  const file = path.join(root, OUTPUT);
  if (check) {
    let actual = null;
    try {
      actual = fs.readFileSync(file, 'utf8');
    } catch {
      /* missing file is drift */
    }
    if (actual === expected) return { ok: true, problems: [], summary: `${OUTPUT} is in sync` };
    return {
      ok: false,
      problems: [`${OUTPUT} is ${actual === null ? 'missing' : 'out of date'}: run node scripts/gen-errors-doc.mjs`],
    };
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, expected);
  return { ok: true, problems: [], summary: `wrote ${OUTPUT}` };
}

if (isMain(import.meta.url)) {
  const { root, flags } = parseArgs(process.argv.slice(2), import.meta.url);
  const result = run(root, { check: flags.has('--check') });
  if (result.ok) {
    console.log(`gen-errors-doc: ${result.summary}`);
  } else {
    console.error('gen-errors-doc: FAILED');
    for (const p of result.problems) console.error(`  - ${p}`);
    process.exit(1);
  }
}
